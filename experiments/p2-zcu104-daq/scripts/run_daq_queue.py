"""Run bounded-queue faults and measured host callback workloads using RTL payload."""

import argparse
import csv
import json
import os
from pathlib import Path
import subprocess
import sys

from run_sim import ROOT, run_logged


def csv_run(command, matrix_path, log_path, env):
    with matrix_path.open("w", encoding="utf-8", newline="") as matrix, \
            log_path.open("w", encoding="utf-8") as log:
        log.write("COMMAND " + json.dumps(command, ensure_ascii=False) + "\n")
        log.flush()
        result = subprocess.run(command, cwd=ROOT, env=env, stdout=matrix, stderr=log, timeout=60)
        log.write(f"\nEXIT_CODE {result.returncode}\n")
    if result.returncode:
        raise RuntimeError(f"Command failed; evidence retained in {log_path}")
    with matrix_path.open(encoding="utf-8", newline="") as matrix:
        return list(csv.DictReader(matrix))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("results/daq_queue"))
    parser.add_argument("--capture", type=Path, help="Reuse an existing RTL capture inside this experiment; skips upstream regression")
    parser.add_argument("--wsl-distro", default="Ubuntu-22.04")
    parser.add_argument("--iverilog")
    args = parser.parse_args()
    output = (ROOT / args.output).resolve()
    output.relative_to(ROOT)
    output.mkdir(parents=True, exist_ok=True)
    (ROOT / "build").mkdir(exist_ok=True)
    relative = output.relative_to(ROOT).as_posix()
    env = os.environ.copy()
    if args.capture:
        capture = (ROOT / args.capture).resolve()
        capture.relative_to(ROOT)
        provenance = "caller-supplied existing capture; not regenerated by this invocation"
    else:
        command = [sys.executable, "scripts/run_daq_session.py", "--output", relative + "/upstream",
                   "--wsl-distro", args.wsl_distro]
        if args.iverilog:
            command.extend(["--iverilog", args.iverilog])
        run_logged(command, output / "upstream_runner.log", env)
        capture = output / "upstream/receiver/capture/rtl_capture_le.bin"
        provenance = "fresh actual RTL capture via run_daq_session.py; upstream regressions included"
    if capture.stat().st_size != 336:
        raise RuntimeError("Expected the complete 12-frame/336-byte capture")
    capture_arg = capture.relative_to(ROOT).as_posix()
    prefix = []
    if os.name == "nt":
        linux_root = subprocess.check_output(
            ["wsl", "-d", args.wsl_distro, "--exec", "wslpath", "-a", str(ROOT)],
            cwd=ROOT, text=True, encoding="utf-8", timeout=30).strip()
        prefix = ["wsl", "-d", args.wsl_distro, "--cd", linux_root, "--exec"]
    common = ["-std=c11", "-Wall", "-Wextra", "-Werror", "-Wpedantic", "-Ips", "-Itests",
              "ps/frame_validator.c", "ps/simple_s2mm.c", "ps/daq_session.c", "ps/daq_queue.c",
              "tests/queue_host.c"]
    run_logged(prefix + ["gcc", "-O1", "-g", "-fsanitize=address,undefined", "-fno-sanitize-recover=all",
                        "-fno-omit-frame-pointer"] + common + ["tests/test_daq_queue.c", "-o", "build/test_daq_queue"],
               output / "c_compile.log", env)
    cases = csv_run(prefix + ["./build/test_daq_queue", capture_arg], output / "fault_matrix.csv",
                    output / "c_test.log", env)
    if len(cases) != 13 or any(row["result"] != "PASS" for row in cases):
        raise RuntimeError("Queue matrix failed or incomplete")
    run_logged(prefix + ["gcc", "-O2"] + common + ["tests/bench_daq_queue.c", "-o", "build/bench_daq_queue"],
               output / "benchmark_compile.log", env)
    measurements = csv_run(prefix + ["./build/bench_daq_queue", capture_arg, relative + "/first_epoch_latency.csv"],
                           output / "host_measurements.csv", output / "benchmark.log", env)
    if len(measurements) != 9 or any(
            row["result"] != "PASS"
            or int(row["rtl_replay_epochs"]) != (100000 if int(row["consumer_hold_us"]) == 0 else 20)
            or int(row["frames"]) != int(row["rtl_replay_epochs"]) * 12
            or int(row["valid_bytes"]) != int(row["frames"]) * 28
            or int(row["process_cpu_ns"]) <= 0 for row in measurements):
        raise RuntimeError("Host measurement matrix failed or incomplete")
    summary = {"scope": "bounded CPU queue with one DMA work buffer; host callbacks only",
               "capture": capture_arg, "provenance": provenance,
               "cases": len(cases), "passed": len(cases), "sanitizers": ["address", "undefined"],
               "host_measurement_cases": len(measurements), "capacities": [1, 3, 8],
               "consumer_hold_us_requested": [0, 200, 1000],
               "rtl_replay_epochs": {"zero_wait": 100000, "with_wait": 20},
               "measurement_clock": "CLOCK_MONOTONIC", "measurement_build": "gcc -O2, without sanitizers",
               "process_cpu_clock": "CLOCK_PROCESS_CPUTIME_ID",
               "process_cpu_pct_definition": "100 * process_cpu_ns / elapsed_ns; not system CPU load",
               "hardware_dma_executed": False, "process_cpu_time_measured": True,
               "system_cpu_load_measured": False}
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(f"PASS {len(cases)} queue cases; {len(measurements)} host measurements; evidence: {output}")


if __name__ == "__main__":
    main()
